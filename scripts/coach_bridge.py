#!/usr/bin/env python3
"""
Antigravity Coaching Bridge for GoCoach macOS App.

Supports a 3-tier coaching pipeline over JSON Lines (stdin/stdout):
1. Live Antigravity Session Bridge (`.coach_ipc/`): Connects to ANY active
   Antigravity conversation opened in the workspace (via the workspace
   `GEMINI.md` / `go-coach` skill) — zero API keys required and not tied to any
   specific conversation ID.
2. `google-antigravity` Python SDK (`Agent` with `LocalAgentConfig` / Vertex /
   `LocalOpenAIAgentConfig`) when ambient credentials or local LLM are present.
3. Instant KataGo Tactical & Human-SL Coach: Deep geometric + ownership +
   human-rank probability analysis when running completely offline with no
   Antigravity window open.
"""

import asyncio
import json
import os
import pathlib
import sys
import time
import traceback
from typing import Any, Optional

try:
    from google.antigravity import (
        Agent,
        CapabilitiesConfig,
        CustomSystemInstructions,
        LocalAgentConfig,
        LocalOpenAIAgentConfig,
    )
    HAS_AGY_SDK = True
except ImportError:
    Agent = Any  # type: ignore[misc,assignment]
    HAS_AGY_SDK = False

WORKSPACE_DIR = pathlib.Path(
    os.environ.get("GOCOACH_WORKSPACE", str(pathlib.Path(__file__).resolve().parent.parent))
)
IPC_DIR = WORKSPACE_DIR / ".coach_ipc"
REQUEST_FILE = IPC_DIR / "pending_request.json"
RESPONSE_FILE = IPC_DIR / "response.json"
HEARTBEAT_FILE = IPC_DIR / "agent_heartbeat.json"

GO_COACH_SYSTEM_PROMPT = """You are a friendly, insightful Go (Weiqi/Baduk) teacher coaching a student during a live game.
You receive compact tactical digests generated by KataGo.

Guidelines:
1. Keep advice concise: 2 to 4 sentences maximum unless the student asks a detailed follow-up question.
2. Focus on human Go concepts: liberties, cutting points, good/bad shape (empty triangle, bamboo joint, tiger's mouth, hane at the head of two stones), urgent vs. big moves, direction of play, and group safety/eyespace.
3. Do NOT recite long lists of coordinates; the student can already click the Principal Variation (PV) branches directly on the board. Mention only 1-2 key coordinates to anchor your explanation.
4. Calibrate your explanation to the student's rank provided in the digest. Be encouraging and clear."""


def emit(payload: dict[str, Any]) -> None:
    sys.stdout.write(json.dumps(payload, ensure_ascii=False) + "\n")
    sys.stdout.flush()


class SDKCoachManager:
    """Manages google-antigravity SDK Agent when credentials or local endpoints exist."""

    def __init__(self) -> None:
        self._agent: Optional[Agent] = None
        self._last_digest: Optional[str] = None

    def is_configured(self) -> bool:
        return HAS_AGY_SDK and bool(
            os.environ.get("GEMINI_API_KEY")
            or (
                os.environ.get("GOOGLE_CLOUD_PROJECT")
                and os.environ.get("GOOGLE_CLOUD_LOCATION")
            )
            or os.environ.get("GOCOACH_OPENAI_BASE_URL")
        )

    def _make_config(self) -> Any:
        instructions = CustomSystemInstructions(
            title="GoCoach",
            text=GO_COACH_SYSTEM_PROMPT,
        )
        caps = CapabilitiesConfig(
            enable_subagents=False,
            enabled_tools=[],
        )
        openai_url = os.environ.get("GOCOACH_OPENAI_BASE_URL")
        if openai_url:
            return LocalOpenAIAgentConfig(
                base_url=openai_url,
                model=os.environ.get("GOCOACH_OPENAI_MODEL", "gemma3"),
                system_instructions=instructions,
                capabilities=caps,
            )
        return LocalAgentConfig(
            system_instructions=instructions,
            capabilities=caps,
        )

    async def ensure_agent(self, reset: bool = False) -> Agent:
        if reset and self._agent is not None:
            try:
                await self._agent.__aexit__(None, None, None)
            except Exception:
                pass
            self._agent = None

        if self._agent is None:
            agent = Agent(self._make_config())
            await agent.__aenter__()
            self._agent = agent
        return self._agent

    async def close(self) -> None:
        if self._agent is not None:
            try:
                await self._agent.__aexit__(None, None, None)
            except Exception:
                pass
            self._agent = None


def is_antigravity_ipc_active() -> bool:
    """Checks if an Antigravity agent session has an active listener heartbeat."""
    try:
        if not HEARTBEAT_FILE.exists():
            return False
        data = json.loads(HEARTBEAT_FILE.read_text(encoding="utf-8"))
        ts = float(data.get("timestamp", 0))
        # Active if heartbeat updated within the last 120 seconds
        return (time.time() - ts) < 120.0
    except Exception:
        return False


async def query_antigravity_ipc(
    req_id: str, req_type: str, digest: str, question: str, timeout_sec: float = 18.0
) -> Optional[str]:
    """Dispatches a compact coaching request to any attached Antigravity session via IPC."""
    IPC_DIR.mkdir(parents=True, exist_ok=True)
    try:
        if RESPONSE_FILE.exists():
            RESPONSE_FILE.unlink()
    except OSError:
        pass

    payload = {
        "id": req_id,
        "type": req_type,
        "digest": digest,
        "question": question,
        "created_at": time.time(),
    }
    tmp_req = IPC_DIR / f"pending_request_{req_id}.tmp"
    tmp_req.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    tmp_req.replace(REQUEST_FILE)

    deadline = time.time() + timeout_sec
    last_partial = ""
    while time.time() < deadline:
        await asyncio.sleep(0.15)
        if RESPONSE_FILE.exists():
            try:
                resp = json.loads(RESPONSE_FILE.read_text(encoding="utf-8"))
                if resp.get("id") != req_id:
                    continue
                partial = resp.get("partial_text", "")
                if partial and len(partial) > len(last_partial):
                    delta = partial[len(last_partial) :]
                    last_partial = partial
                    emit({"id": req_id, "event": "chunk", "text": delta})
                if resp.get("done"):
                    full_text = resp.get("text", "").strip()
                    if full_text and len(full_text) > len(last_partial):
                        emit({"id": req_id, "event": "chunk", "text": full_text[len(last_partial) :]})
                    try:
                        RESPONSE_FILE.unlink()
                        if REQUEST_FILE.exists():
                            REQUEST_FILE.unlink()
                    except OSError:
                        pass
                    return full_text
            except Exception:
                continue
    return None


def synthesize_tactical_coaching(req: dict[str, Any]) -> str:
    """
    Synthesizes human-understandable Go advice from the structured tactical fields
    and KataGo / Human-SL analysis when running standalone without an external LLM.
    """
    meta = req.get("meta", {})
    req_type = req.get("type", "advice")
    question = (req.get("question") or "").strip()

    played_move = meta.get("playedMove", "that move")
    best_move = meta.get("bestMove", "the suggested alternative")
    second_move = meta.get("secondMove")
    score_loss = float(meta.get("scoreLoss", 0.0))
    winrate_drop = float(meta.get("winrateDropPercent", 0.0))
    phase = meta.get("phase", "middle game")
    tactical_tags: list[str] = meta.get("tacticalTags", [])
    ownership_shifts: list[str] = meta.get("ownershipShifts", [])
    pv_outcomes: list[str] = meta.get("pvOutcomes", [])
    counterfactual_notes: list[str] = meta.get("counterfactualNotes", [])
    best_pv: list[str] = meta.get("bestPV", [])
    punish_pv: list[str] = meta.get("punishPV", [])
    human_prob = meta.get("playedHumanProb")
    best_human_prob = meta.get("bestHumanProb")
    player_rank = meta.get("playerRank", "10k")
    severity = meta.get("severity", "mistake")

    if req_type == "followup" and question:
        if counterfactual_notes:
            cf_summary = " ".join(n.lstrip("- ") for n in counterfactual_notes)
            return (
                f"KataGo checked that exact variation: {cf_summary}. "
                f"I also added an 'Asked' variation branch above so you can click it and step through the sequence on the board!"
            )
        q_lower = question.lower()
        if "why" in q_lower and best_move.lower() in q_lower:
            pv_preview = " -> ".join(best_pv[:4]) if best_pv else best_move
            return (
                f"Playing at {best_move} works because it seizes the key shape point before the opponent can settle. "
                f"KataGo expects the continuation {pv_preview}, which keeps your stones connected and preserves roughly "
                f"{max(score_loss, 1.5):.1f} points of value compared to {played_move}."
            )
        if "cut" in q_lower or "connect" in q_lower or "libert" in q_lower:
            return (
                f"In this local fight, {best_move} directly addresses the liberty and cutting-point balance, whereas "
                f"{played_move} leaves a weakness that the opponent can exploit via {' -> '.join(punish_pv[:3]) if punish_pv else best_move}. "
                f"Try stepping through the green variation on the board to see how the stones stay connected."
            )
        if "score" in q_lower or "win" in q_lower or "ahead" in q_lower or "behind" in q_lower:
            lead = float(meta.get("scoreLeadAfter", 0.0))
            leader = "Black" if lead >= 0 else "White"
            return (
                f"Currently {leader} leads by about {abs(lead):.1f} points in the {phase}. "
                f"The top priority right now is playing at {best_move} to stabilize the local balance and avoid giving away free forcing moves."
            )
        pv_str = " -> ".join(best_pv[:4]) if best_pv else best_move
        return (
            f"Looking at this {phase} position, {best_move} is the cleanest continuation (envisioning {pv_str}). "
            f"Click the variation branches above to step through how KataGo handles the local response."
        )

    # Check if this was an on-demand "Ask Coach" when the player hasn't blundered
    if score_loss < 1.5 and winrate_drop < 5.0:
        lead = float(meta.get("scoreLeadAfter", 0.0))
        leader = "Black" if lead >= 0 else "White"
        pv_str = " -> ".join(best_pv[:3]) if best_pv else best_move
        if played_move and played_move != "none":
            return (
                f"Nice move! {played_move} is right in line with KataGo's top recommendation ({leader} leads by ~{abs(lead):.1f} pts). "
                f"Going forward in this {phase}, keep an eye on {best_move} ({pv_str}) as the next key focus area."
            )
        return (
            f"In this {phase} position ({leader} +{abs(lead):.1f} pts), the highest-value point on the board is {best_move}. "
            + (f"A solid secondary option is {second_move}. " if second_move else "")
            + "Click the variation pills below to preview the expected sequence on the board."
        )

    # Build a rich, human-oriented explanation of the mistake/blunder
    reasons: list[str] = []
    if "self_atari" in tactical_tags:
        reasons.append(f"playing at {played_move} puts your own stones into shortage of liberties (damezumari / self-atari)")
    elif "missed_atari_defense" in tactical_tags:
        reasons.append(f"{played_move} overlooks a true urgent atari on your group that KataGo's {best_move} rescues")
    elif "saved_non_sente_atari" in tactical_tags:
        reasons.append(f"{played_move} rescues small or dead stones in atari that were not urgent (not sente), giving up global initiative")
    elif "played_non_sente_atari" in tactical_tags:
        reasons.append(f"the atari at {played_move} is not truly forcing (not sente)—the opponent can ignore it (tenuki) to take a much bigger point")
    elif "empty_triangle" in tactical_tags:
        reasons.append(f"{played_move} forms an inefficient empty triangle, concentrating your stones without gaining eyespace or liberties")
    elif "allowed_opponent_wedge_or_cut" in tactical_tags:
        reasons.append(f"{played_move} leaves a gap where the opponent can immediately wedge or cut between your stones")
    elif "allowed_opponent_hane_at_head_of_two" in tactical_tags:
        reasons.append(f"{played_move} lets the opponent play a painful 'hane at the head of two stones' to cramp your shape")
    elif "allowed_opponent_peep" in tactical_tags:
        reasons.append(f"{played_move} exposes a one-point jump to a severe peep (nozoki) that makes your stones heavy")
    elif "missed_cut_or_connection" in tactical_tags:
        reasons.append(f"{played_move} leaves an important cutting point exposed in the local shape")
    elif "tenuki_from_urgent" in tactical_tags:
        reasons.append(f"playing away at {played_move} leaves an urgent local fight unfinished")
    elif "overplay_invasion" in tactical_tags:
        reasons.append(f"{played_move} pushes too deeply into the opponent's sphere of influence without enough support")
    elif "slow_endgame" in tactical_tags:
        reasons.append(f"in the {phase}, {played_move} is a bit slow compared to the largest remaining boundary points")
    elif "direction_of_play" in tactical_tags:
        reasons.append(f"in the {phase}, {played_move} is smaller than the main global direction-of-play point on the open side/corner")

    if not reasons:
        if phase == "opening":
            reasons.append(f"in the opening, {played_move} is locally passive and lets the opponent take the initiative on the wider board")
        elif phase == "endgame":
            reasons.append(f"in the endgame, {played_move} misses a larger sente or territory-defining point")
        else:
            reasons.append(f"{played_move} loses local efficiency and allows the opponent a severe follow-up")

    shape_bonus = ""
    if "missed_sente_atari" in tactical_tags:
        shape_bonus = f" — delivering a true sente (forcing) atari that the opponent must answer locally"
    elif "missed_hane_at_head_of_two" in tactical_tags:
        shape_bonus = f" — following the proverb 'play hane at the head of two stones' to take command of the fight"
    elif "missed_tigers_mouth" in tactical_tags:
        shape_bonus = f" — forming a resilient Tiger's Mouth (kake-tsugi) to protect your cutting points and eye space"
    elif "missed_bamboo_joint" in tactical_tags:
        shape_bonus = f" — completing an unbreakable Bamboo Joint (takefu) connection"
    elif "missed_peep_one_point_jump" in tactical_tags:
        shape_bonus = f" — peeping (nozoki) at the opponent's one-point jump to force heavy shape"

    punish_first = punish_pv[1] if len(punish_pv) > 1 else (best_pv[0] if best_pv else best_move)
    sentence1 = (
        f"Playing {played_move} is a {severity} (-{score_loss:.1f} pts, -{winrate_drop:.0f}% winrate) because {reasons[0]}."
    )
    if ownership_shifts:
        sentence1 += f" ({ownership_shifts[0]}.)"
    elif pv_outcomes:
        sentence1 += f" ({pv_outcomes[0]}.)"

    sentence2 = (
        f"Instead, {best_move} is much stronger here{shape_bonus} before the opponent can punish around {punish_first}."
    )

    sentence3 = ""
    if human_prob is not None and best_human_prob is not None and human_prob >= 0.08:
        sentence3 = (
            f" (At the {player_rank} level, players are tempted by {played_move} about {human_prob * 100:.0f}% of the time, "
            f"so spotting {best_move} is a great habit to build!)"
        )
    elif second_move:
        sentence3 = f" If you prefer a simpler variation, {second_move} is also a playable alternative."

    return f"{sentence1} {sentence2}{sentence3}"


async def handle_request(sdk_manager: SDKCoachManager, req: dict[str, Any]) -> None:
    req_id = req.get("id", "unknown")
    req_type = req.get("type", "advice")

    if req_type == "ping":
        mode = "antigravity_ipc" if is_antigravity_ipc_active() else (
            "antigravity_sdk" if sdk_manager.is_configured() else "katago_tactical_coach"
        )
        emit({"id": req_id, "event": "pong", "mode": mode})
        return

    if req_type == "reset":
        await sdk_manager.close()
        emit({"id": req_id, "event": "done", "full_text": ""})
        return

    digest = req.get("digest", "")
    question = req.get("question", "")

    # Tier 1: Live Antigravity Session via IPC (if an Antigravity agent is listening)
    if is_antigravity_ipc_active():
        ipc_text = await query_antigravity_ipc(req_id, req_type, digest, question)
        if ipc_text:
            emit({"id": req_id, "event": "done", "full_text": ipc_text, "source": "antigravity_ipc"})
            return

    # Tier 2: google-antigravity SDK (if API key / Vertex / Local OpenAI configured)
    if sdk_manager.is_configured():
        try:
            reset_session = bool(req.get("reset_session", req_type == "advice"))
            agent = await sdk_manager.ensure_agent(reset=reset_session)

            if req_type == "advice":
                sdk_manager._last_digest = digest
                prompt = digest
            elif req_type == "followup":
                if reset_session and digest:
                    prompt = f"{digest}\n\nStudent question: {question}"
                elif digest and digest != sdk_manager._last_digest:
                    sdk_manager._last_digest = digest
                    prompt = f"[Updated Board Context]\n{digest}\n\nStudent question: {question}"
                else:
                    prompt = f"Student follow-up question: {question} (Keep your answer concise and focused on the current board position.)"
            else:
                prompt = digest or question

            response = await agent.chat(prompt)
            full_chunks: list[str] = []
            async for token in response:
                if token:
                    full_chunks.append(token)
                    emit({"id": req_id, "event": "chunk", "text": token})

            full_text = "".join(full_chunks).strip()
            emit({"id": req_id, "event": "done", "full_text": full_text, "source": "antigravity_sdk"})
            return
        except Exception:
            # Fall through gracefully to Tier 3 if SDK call fails
            pass

    # Tier 3: Instant KataGo Tactical & Human-SL Coach synthesis
    try:
        text = synthesize_tactical_coaching(req)
        # Stream word-by-word briefly for smooth UI feel
        words = text.split(" ")
        chunk_size = 4
        for i in range(0, len(words), chunk_size):
            piece = " ".join(words[i : i + chunk_size])
            if i + chunk_size < len(words):
                piece += " "
            emit({"id": req_id, "event": "chunk", "text": piece})
            await asyncio.sleep(0.015)
        emit({"id": req_id, "event": "done", "full_text": text, "source": "katago_tactical_coach"})
    except Exception as exc:
        emit({
            "id": req_id,
            "event": "error",
            "error": f"{type(exc).__name__}: {exc}",
            "traceback": traceback.format_exc(),
        })


async def main() -> None:
    IPC_DIR.mkdir(parents=True, exist_ok=True)
    sdk_manager = SDKCoachManager()
    emit({"id": "init", "event": "ready"})

    loop = asyncio.get_running_loop()
    reader = asyncio.StreamReader()
    protocol = asyncio.StreamReaderProtocol(reader)
    await loop.connect_read_pipe(lambda: protocol, sys.stdin)

    try:
        while True:
            line = await reader.readline()
            if not line:
                break
            raw = line.decode("utf-8", errors="replace").strip()
            if not raw:
                continue
            try:
                req = json.loads(raw)
            except json.JSONDecodeError as err:
                emit({"id": "unknown", "event": "error", "error": f"Invalid JSON: {err}"})
                continue

            await handle_request(sdk_manager, req)
    finally:
        await sdk_manager.close()


if __name__ == "__main__":
    try:
        asyncio.run(main())
    except KeyboardInterrupt:
        pass
